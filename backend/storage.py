"""Storage layer.

All file bytes go through a StorageBackend. Today that is LocalStorage (a folder
on disk). To move to cloud object storage (AWS S3, Cloudflare R2, Supabase
Storage, ...) you write one new class with the same four methods and change
`storage = ...` at the bottom. Routes never touch the filesystem directly.
"""
import os
import re
import uuid
from pathlib import Path
from typing import BinaryIO, Iterator

from config import UPLOAD_DIR


class StorageBackend:
    def save(self, key: str, data: BinaryIO, max_bytes: int) -> int:
        """Store the stream under `key`. Returns bytes written. Raises FileTooLarge."""
        raise NotImplementedError

    def open(self, key: str) -> Iterator[bytes]:
        raise NotImplementedError

    def exists(self, key: str) -> bool:
        raise NotImplementedError

    def delete(self, key: str) -> None:
        raise NotImplementedError


class FileTooLarge(Exception):
    pass


class LocalStorage(StorageBackend):
    CHUNK = 1024 * 1024  # 1 MB

    def __init__(self, root: Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        # Keys are generated by us (uuid + ext), but resolve and check anyway so a
        # bad key can never escape the uploads folder.
        path = (self.root / key).resolve()
        if path.parent != self.root:
            raise ValueError("Invalid storage key")
        return path

    def save(self, key: str, data: BinaryIO, max_bytes: int) -> int:
        path = self._path(key)
        written = 0
        try:
            with open(path, "wb") as out:
                while chunk := data.read(self.CHUNK):
                    written += len(chunk)
                    if written > max_bytes:
                        raise FileTooLarge()
                    out.write(chunk)
        except Exception:
            path.unlink(missing_ok=True)  # never leave half-written files behind
            raise
        return written

    def open(self, key: str) -> Iterator[bytes]:
        with open(self._path(key), "rb") as f:
            while chunk := f.read(self.CHUNK):
                yield chunk

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


def sanitize_filename(name: str) -> str:
    """Strip any directory parts and unsafe characters from a user-supplied name.
    '../../etc/passwd' -> 'passwd'; 'C:\\x\\a b.pdf' -> 'a b.pdf'."""
    name = name.replace("\\", "/").split("/")[-1]
    name = re.sub(r"[^\w\s.\-()]", "_", name).strip().strip(".")
    return name[:200]


def make_stored_name(original: str) -> str:
    """Unique name on disk: random UUID + original extension."""
    ext = os.path.splitext(original)[1].lower()
    return f"{uuid.uuid4().hex}{ext}"


storage: StorageBackend = LocalStorage(UPLOAD_DIR)
